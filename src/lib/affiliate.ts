import { marketplaces, type MarketplaceKey } from "@/config/affiliate";

export type AffiliateLinkResult =
  | { ok: true; url: string; marketplace: MarketplaceKey; kind: "product" | "short-link" }
  | { ok: false; reason: string };

const ASIN = /^[A-Z0-9]{10}$/;

/** Extract an ASIN from the standard Amazon product path formats. */
export function extractAsin(pathname: string): string | null {
  const match =
    pathname.match(/\/dp\/([A-Z0-9]{10})(?:[/?]|$)/i) ??
    pathname.match(/\/gp\/product\/([A-Z0-9]{10})(?:[/?]|$)/i) ??
    pathname.match(/\/gp\/aw\/d\/([A-Z0-9]{10})(?:[/?]|$)/i);
  const asin = match?.[1]?.toUpperCase();
  return asin && ASIN.test(asin) ? asin : null;
}

/**
 * Build the outbound affiliate URL for a product destination.
 *
 * - Full product URLs must point at the configured marketplace and contain a
 *   real ASIN path copied from Amazon (never guessed). They are normalized to
 *   `https://<host>/dp/<ASIN>?tag=<trackingId>` so the configured tracking ID
 *   is always the one used.
 * - `amzn.to` short links generated by Amazon's SiteStripe already embed the
 *   tracking ID chosen when they were created; they are passed through as-is
 *   and must be generated while signed in to the correct Associates account.
 *
 * Anything else is rejected, which hides the CTA instead of rendering a
 * broken or misleading link.
 */
export function buildAffiliateUrl(
  destination: string | undefined,
  marketplaceKey: MarketplaceKey,
): AffiliateLinkResult {
  if (!destination) return { ok: false, reason: "No verified destination URL" };
  const marketplace = marketplaces[marketplaceKey];
  if (!marketplace) return { ok: false, reason: `Unknown marketplace ${marketplaceKey}` };

  let parsed: URL;
  try {
    parsed = new URL(destination);
  } catch {
    return { ok: false, reason: "Destination is not a valid URL" };
  }
  if (parsed.protocol !== "https:") return { ok: false, reason: "Destination must use https" };

  const host = parsed.hostname.toLowerCase();

  if (marketplace.shortLinkHosts.includes(host)) {
    if (!/^\/[A-Za-z0-9]{4,12}$/.test(parsed.pathname)) {
      return { ok: false, reason: "Malformed short link" };
    }
    return { ok: true, url: `https://${host}${parsed.pathname}`, marketplace: marketplace.key, kind: "short-link" };
  }

  if (!marketplace.hosts.includes(host)) {
    return { ok: false, reason: `Host ${host} does not belong to ${marketplace.label}` };
  }

  const asin = extractAsin(parsed.pathname);
  if (!asin) return { ok: false, reason: "No ASIN found in product URL" };

  const url = new URL(`https://${marketplace.canonicalHost}/dp/${asin}`);
  url.searchParams.set("tag", marketplace.trackingId);
  return { ok: true, url: url.toString(), marketplace: marketplace.key, kind: "product" };
}
